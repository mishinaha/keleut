import sys
p=sys.argv[1]
s=open(p,encoding='utf-8').read()
def rep(a,b):
    global s
    assert s.count(a)==1, a
    s=s.replace(a,b)
rep("""文法に合わないトークンが前のトークンより後ろの行にあるときは、前のトークンの終わりを主な位置にし、
合わなかったトークンの位置を括弧の中に添える。
""","""前のトークンが続きを求めていて(行末の演算子やカンマ、括弧の中)、文法に合わないトークンが
それより後ろの行にあるときは、前のトークンの終わりを主な位置にし、
合わなかったトークンの位置を括弧の中に添える。
""")
rep("""続きの無い二項演算子と、閉じていない括弧は、前のトークンの終わりを指す:
""","""続きの無い二項演算子、閉じていない括弧、括弧の中のカンマの抜けは、前のトークンの終わりを指す:
""")
rep("""  paren.kel:1:14: パースエラー(この位置の後ろ、3:1 のトークンが文法に合いません)
  [2]

合わないトークンそのものが誤りのときも、主な位置は前のトークンの終わりで、
合わないトークンの位置は括弧の中にある:

  $ printf 'let x = 1\\n)\\n' > stray.kel
  $ diktor stray.kel
  stray.kel:1:10: パースエラー(この位置の後ろ、2:1 のトークンが文法に合いません)
  [2]
""","""  paren.kel:1:14: パースエラー(この位置の後ろ、3:1 のトークンが文法に合いません)
  [2]
  $ printf 'let f(a, b) = a\\nlet y = f(\\n  1\\n  2\\n)\\n' > comma.kel
  $ diktor comma.kel
  comma.kel:3:4: パースエラー(この位置の後ろ、4:3 のトークンが文法に合いません)
  [2]

前のトークンが文を終えられ、括弧の外にあるときは、行頭の余った閉じ括弧そのものを指す:

  $ printf 'let x = 1\\n)\\n' > stray.kel
  $ diktor stray.kel
  stray.kel:2:1: パースエラー(付近のトークンを確認してください)
  [2]
  $ printf 'let f() = {\\n  let x = 1\\n  x\\n}\\n}\\n' > strayb.kel
  $ diktor strayb.kel
  strayb.kel:5:1: パースエラー(付近のトークンを確認してください)
  [2]
""")
rep("""  b : Int32 = 2
""","""  b : Int32 = 2

括弧の中で続きを待った入力が次の行で合わなくなったときも、前のトークンの終わりを指す:

  $ printf 'let x = (1 +\\n)\\nlet y = 2\\n' | diktor --repl
  <stdin>:1:13: パースエラー(この位置の後ろ、2:1 のトークンが文法に合いません)
  y : Int32 = 2
""")
open(p,'w',encoding='utf-8').write(s)
