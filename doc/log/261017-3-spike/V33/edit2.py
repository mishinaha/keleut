import sys
p=sys.argv[1]
s=open(p,encoding='utf-8').read()
def rep(old,new):
    global s
    assert s.count(old)==1, old[:60]
    s=s.replace(old,new)
rep('''          (* 実装が最外の @ を自分で書いていれば、空でない行はその注釈に由来し、
             本体が何も起こしていなくても落ちる。そのときは本体ではなく注釈を指す *)
          let culprit =
            if outer_eff_written (snd bnode) then " の注釈が空でない行を書いています。元の報告: "
            else " の本体がエフェクトを起こしています。元の報告: "
          in
''','''          (* 実装が最外の @ を自分で書いていれば、空でない行はその注釈に由来し、
             本体が何も起こしていなくても落ちる。そのときは本体ではなく注釈を指す。
             最外の @ を書いていない値束縛の行は、初期化式の値の型から来るので、
             本体とも注釈とも言わない *)
          let culprit =
            let b = snd bnode in
            if outer_eff_written b then " の注釈に @ {} 以外の行を書いています。元の報告: "
            else
              match b.T.lb_params with
              | Some _ -> " の本体がエフェクトを起こしています。元の報告: "
              | None -> " の初期化式の値の型の最外の行が空ではありません。元の報告: "
          in
''')
rep('''   このときは「本体がエフェクトを起こしています」ではなく
   「注釈が空でない行を書いています」と述べる(clsannotrow)。
   本体が実際に `Print` を起こしていても、注釈を外せば本体の行が残って前者の文言になるので、
   注釈の側を先に述べて嘘にならない。
   最外の `@` を書いていなければ、実装の行は本体から推論したものなので、
   空でない行は本体が何かを起こしたことを意味する。
   型エイリアスを頭に書いた値束縛の注釈は、`outer_eff_written` が `@` を書いた側に倒すので、
   エイリアスの中の `@ Print` も注釈の側として述べる(clsannotalias)。
''','''   このときは「本体がエフェクトを起こしています」ではなく
   「注釈に `@ {}` 以外の行を書いています」と述べる(clsannotrow)。
   本体が実際に `Print` を起こしていても、注釈を外せば本体の行が残って後者の文言になるので、
   注釈の側を先に述べて嘘にならない。
   注釈が書いたのが行変数 `@ F` で、引数の型を通して宣言の行変数に結ばれたために
   空にならない形も、この文言で述べる。
   `@ F` を `@ {}` に書き換えれば、その形も通る。
   型エイリアスを頭に書いた値束縛の注釈は、`outer_eff_written` が `@` を書いた側に倒すので、
   エイリアスの中の `@ Print` も注釈の側として述べる(clsannotalias)。
   関数束縛が最外の `@` を書いていなければ、実装の行は本体から推論したものなので、
   空でない行は本体が何かを起こしたことを意味する。
   値束縛が最外の `@` を書いていなければ、実装の行は初期化式の値の型から来る。
   `let size = sizeP` のように、`@ Print` と注釈した関数を名前で渡すだけでも行は空でなくなり、
   このとき本体は何も起こしていない。
   そこでこの形は「初期化式の値の型の最外の行が空ではありません」と述べる(clsvalrow)。
''')
open(p,'w',encoding='utf-8').write(s)
